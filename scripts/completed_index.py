"""The index of the completed challenges.

The open challenges have their index: `PENDING.md`. The solved ones
deserve the same — and for a reason that is not only symmetry.

A solved file leaves the working tree: the sync removes it (through the
git `skip-worktree` flag) once the resolution is pushed. The relative
path of `PENDING.md` would therefore point to nothing here. The index of
the completed challenges links to where the file actually lives: the
absolute URL of the file in the repository, and the repository itself.

The ledger is the source of truth. The index is only a projection of it.
"""

import subprocess
from datetime import datetime
from pathlib import Path
from urllib.parse import urlsplit

COMPLETED_FILE = "COMPLETED.md"

HEADER = """# Completed challenges

> Generated by the notebook sync — do not edit by hand, the next sync
> replaces this file.
"""

FOOTER = (
    "The challenges still open are in [PENDING.md](PENDING.md)."
)

COLUMNS = (
    "| Challenge | Solved | ID | Title | Difficulty | Topics |"
    " Resolution | Repository | File |"
)
SEPARATOR = "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"


def _format_resolution(hours) -> str:
    """The time between the pickup and the solution, for a human.

    The ledger carries it in hours, as a float. A number of hours is
    not something anyone reads at a glance.
    """
    if hours is None:
        return ""

    seconds = float(hours) * 3600

    if seconds < 3600:
        minutes = int(seconds // 60)
        rest = int(seconds % 60)
        if minutes == 0:
            return f"{rest}s"
        return f"{minutes}m {rest:02d}s"

    if seconds < 86400:
        return f"{seconds / 3600:.1f} h"

    days = seconds / 86400
    if abs(days - round(days)) < 0.05:
        return f"{int(round(days))} days"
    return f"{days:.1f} days"


def _format_solved_date(value, tz=None) -> str:
    """The day the challenge was solved, in the local time of the reader.

    The ledger stores the instant in UTC. The date a human remembers is
    the one on their own clock: a challenge solved at 21:30 BRT belongs
    to the evening of that day, not to the next one.
    """
    if not value:
        return "unknown"

    if isinstance(value, str):
        try:
            value = datetime.fromisoformat(value)
        except ValueError:
            return value

    if not isinstance(value, datetime):
        return str(value)

    if tz is None:
        tz = datetime.now().astimezone().tzinfo

    if value.tzinfo is None:
        return value.strftime("%Y-%m-%d")

    return value.astimezone(tz).strftime("%Y-%m-%d")


def _parse_remote(remote: str) -> tuple[str, str]:
    """The `owner/name` and the web URL of a git remote.

    Both shapes are accepted:
        https://github.com/owner/name.git
        git@github.com:owner/name.git
    """
    remote = (remote or "").strip()
    if not remote:
        return "", ""

    if "@" in remote and ":" in remote.split("@", 1)[1]:
        # git@github.com:owner/name.git
        host, _, path = remote.split("@", 1)[1].partition(":")
    else:
        parts = urlsplit(remote)
        host = parts.netloc
        path = parts.path
        if "@" in host:
            host = host.split("@", 1)[1]

    path = path.strip("/")
    if path.endswith(".git"):
        path = path[: -len(".git")]

    if not host or not path:
        return "", ""

    return path, f"https://{host}/{path}"


def remote_repository(repo: Path) -> tuple[str, str]:
    """The repository where the solutions are kept.

    The remote is the source of truth: the index links to the file where
    it actually lives, and that is the repository the remote points at
    — not a name hardcoded in the script.
    """
    try:
        result = subprocess.run(
            ["git", "-C", str(repo), "remote", "get-url", "origin"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
    except OSError:
        return "", ""

    if result.returncode != 0:
        return "", ""

    return _parse_remote(result.stdout)


def _file_cell(file_path: str, repository_url: str) -> str:
    """The link to the file, where it really is.

    The absolute URL works from anywhere: the local clone does not have
    the file anymore, the repository does.
    """
    if not file_path:
        return "no path in the ledger"

    if not repository_url:
        return f"`{file_path}`"

    return f"[{file_path}]({repository_url}/blob/main/{file_path})"


def render_completed_index(
    rows: list[dict],
    repository: str = "",
    repository_url: str = "",
    tz=None,
) -> str:
    """The content of COMPLETED.md.

    `rows` are the solved problems, most recent first.
    """
    lines = [HEADER]

    if not rows:
        lines.append("Nothing completed yet.")
        lines.append("")
        lines.append(
            "The first solution will show up here, with the time it took"
            " from the pickup to the resolution."
        )
        lines.append("")
        lines.append(FOOTER)
        return "\n".join(lines) + "\n"

    lines.append(COLUMNS)
    lines.append(SEPARATOR)

    for row in rows:
        lines.append(
            "| {challenge} | {solved} | {id} | {title} | {difficulty} |"
            " {topics} | {resolution} | {repository} | {file} |".format(
                challenge=row.get("challenge_date") or "unknown",
                solved=_format_solved_date(row.get("solved_at"), tz),
                id=row.get("id") or "",
                title=row.get("title") or "(no title)",
                difficulty=row.get("difficulty") or "",
                topics=row.get("topics") or "",
                resolution=_format_resolution(row.get("resolution_hours")),
                repository=repository or "unknown",
                file=_file_cell(row.get("file_path") or "", repository_url),
            )
        )

    lines.append("")
    lines.append(
        f"{len(rows)} challenge(s) completed. The full history stays in the"
        " repository and in the ledger."
    )
    lines.append("")
    lines.append(FOOTER)
    return "\n".join(lines) + "\n"


def write_completed_index(repo: Path, content: str) -> bool:
    """Write the index. Returns True when the file changed."""
    path = repo / COMPLETED_FILE
    if path.exists():
        try:
            current = path.read_text(encoding="utf-8")
        except OSError:
            current = None
        if current == content:
            return False

    path.write_text(content, encoding="utf-8")
    return True
