"""The index of the open challenges.

The solutions repository is the cloud: it holds every template and every
solution. The notebook is the desk: it holds the open challenges and
nothing else, because a solved file leaves the working tree.

That makes the working tree sparse. The open challenges are scattered
across the topic folders, and finding "today's" means opening files until
one of them says it was collected today. With more than one challenge
open, it becomes a hunt.

`PENDING.md` is the answer: one file at the root of the repository, with
every open challenge, where its file is and how long it has been
waiting. The sync regenerates it at the end of every run, so it is never
stale.

The ledger is the source of truth. The index is only a projection of it:
if the file and the ledger disagree, the ledger wins.
"""

from datetime import date
from pathlib import Path

PENDING_FILE = "PENDING.md"

HEADER = """# Open challenges

> Generated by the notebook sync — do not edit by hand, the next sync
> replaces this file.
"""


def _waiting_label(challenge_date, today: date) -> str:
    """How long a challenge has been waiting to be solved."""
    if not challenge_date:
        return "unknown"
    days = (today - challenge_date).days
    if days <= 0:
        return "today"
    if days == 1:
        return "1 day"
    return f"{days} days"


def _file_label(row: dict, root: Path | None) -> str:
    """The link to the file, or why it is not here."""
    relative = row.get("file_path")
    if not relative:
        return "no path in the ledger"

    if root is not None and not (root / relative).exists():
        return "not collected yet"

    return f"[{relative}]({relative})"


def render_pending_index(
    rows: list[dict],
    root: Path | None = None,
    today: date | None = None,
    missing_today: str | None = None,
) -> str:
    """The content of PENDING.md.

    `rows` are the open problems, oldest first. `missing_today` names
    the challenge that is live on LeetCode but absent from the ledger.
    """
    today = today or date.today()

    lines = [HEADER]

    if missing_today:
        lines.append(
            f"> **The challenge of today is not collected yet** ({missing_today}). "
            "The cloud is late: the next run of the schedule will fetch it."
        )
        lines.append("")

    if not rows:
        lines.append("Nothing open right now.")
        lines.append("")
        lines.append(
            "The next Daily Challenge arrives here when the cloud publishes it."
        )
        lines.append("")
        lines.append(
            "The challenges already solved are in [COMPLETED.md](COMPLETED.md)."
        )
        return "\n".join(lines) + "\n"

    lines.append("| Collected | ID | Title | Difficulty | Topics | Waiting | File |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- |")

    for row in rows:
        challenge_date = row.get("challenge_date")
        lines.append(
            "| {collected} | {id} | {title} | {difficulty} | {topics} | {waiting} | {file} |".format(
                collected=challenge_date or "unknown",
                id=row.get("id") or "",
                title=row.get("title") or "(no title)",
                difficulty=row.get("difficulty") or "",
                topics=row.get("topics") or "",
                waiting=_waiting_label(challenge_date, today),
                file=_file_label(row, root),
            )
        )

    lines.append("")
    lines.append(
        f"{len(rows)} challenge(s) waiting. Solve one, add the `# Solved` line"
        " at the end of the file, and the next sync sends it and closes it."
    )
    lines.append("")
    lines.append(
        "The challenges already solved are in [COMPLETED.md](COMPLETED.md)."
    )
    return "\n".join(lines) + "\n"


def write_pending_index(repo: Path, content: str) -> bool:
    """Write the index. Returns True when the file changed."""
    path = repo / PENDING_FILE
    if path.exists():
        try:
            current = path.read_text(encoding="utf-8")
        except OSError:
            current = None
        if current == content:
            return False

    path.write_text(content, encoding="utf-8")
    return True
